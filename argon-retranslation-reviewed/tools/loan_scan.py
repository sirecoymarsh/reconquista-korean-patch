KW = re.compile(r'[ァ-ヺ][ァ-ヺー・]*')
ONOMA = re.compile(r'^(.{1,3})\1+$|ッ$|^.ッ.リ$|ー{2,}|(.)\2\2|[ァィゥェォ]{2}|^(.{1,4})\3|^(タッ|ピー|ピピ|ピーブー|ピーポー|チャチャ|チャー|ミーン|トゥル|ジリ|ピリ|ヒュウ|ビュウ|ゴオ|ゴォ|ボォ|ガア|ビョオ|キイ|ザワ|カラカラ)')    # 반복형·ッ 로 끝남·ーー·전화벨·바람 소리

def held(o):
    s, u = o['unit'].split('::')
    if s in SKIP_SCRIPTS: return True
    n = int(u[1:])
    for _, ps, rng in POLICY:
        if ps != s: continue
        a, b = (int(x[1:]) for x in rng.split('-'))
        if a <= n <= b: return True
    return False

if __name__ == '__main__':
    F = [json.loads(l) for l in open(RV / '검수확정_번역필드.jsonl', encoding='utf-8')]
    byunit = collections.defaultdict(list)
    for o in F: byunit[o['unit']].append(o)
    miss = collections.defaultdict(list); have = collections.Counter(); native = collections.Counter(); nheld = collections.Counter()
    for o in F:
        if o['translator_model'] == 'source retained' or o['role'] != 't': continue
        uko = ''.join(x['ko'] for x in byunit[o['unit']])
        for w in dict.fromkeys(KW.findall(o['ja'])):
            w = w.strip('・')
            if len(w) < 2 or w in NOT_LOAN or w in GLOSSARY or ONOMA.search(w): continue
            ok = any(f in uko for f in FORMS[w]) if w in FORMS else present(w, uko)
            if ok: have[w] += 1; continue
            if w in KEEP_NATIVE: native[w] += 1; continue
            if held(o): nheld[w] += 1; continue
            miss[w].append(o['id'])
    rows = sorted(miss.items(), key=lambda x: -len(x[1]))
    json.dump({'miss': miss, 'native': native, 'held': nheld, 'have': have}, open(RV / 'work' / 'loan_scan.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
    print('후보 낱말', len(rows), '후보 자리', sum(len(v) for v in miss.values()), '필드', len({i for v in miss.values() for i in v}))
    print('기본 낱말(KEEP_NATIVE) 자리', sum(native.values()), '보류 구간', sum(nheld.values()))
    print(' '.join(f'{w}:{len(v)}/{len(v) + have[w]}' for w, v in rows))
